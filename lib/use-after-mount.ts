'use client'

import { useEffect } from 'react'

/* ─────────────────────────────────────────────────────────
   마운트 뒤 한 번만

   브라우저에만 있는 것(localStorage · 주소창)을 읽어 화면에 반영하는 자리입니다.
   첫 렌더에 바로 읽지 않고 미루는 이유는 — 서버가 미리 그린 화면과 첫 렌더가
   달라지면 하이드레이션이 어긋나 글자가 깨지기 때문입니다.
   서버에는 localStorage 도 주소창도 없어서 같은 값을 만들어낼 수가 없습니다.

   그래서 effect 안에서 setState 를 합니다. 리액트 규칙이 경고하는 「연쇄 렌더」가
   맞지만 마운트 직후 딱 한 번이고, 대안이 하이드레이션 불일치라 이쪽을 택했습니다.

   ⚠️ 판단을 **여기 한 곳에만** 둡니다. 화면마다 규칙을 꺼버리면 그 틈에 진짜
      연쇄 렌더가 섞여 들어와도 아무도 못 봅니다.
   ───────────────────────────────────────────────────────── */
export function useAfterMount(run: () => void) {
  // eslint-disable-next-line react-hooks/exhaustive-deps
  useEffect(run, [])
}
